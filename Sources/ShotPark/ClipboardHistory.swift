import AppKit
import CryptoKit

extension Notification.Name {
    static let clipboardHistoryChanged = Notification.Name("ShotPark.clipboardHistoryChanged")
}

/// Keeps the most recent images that were copied to the clipboard (by ShotPark or any other app),
/// as PNG files in ~/Library/Application Support/ShotPark/Clipboard. Nothing leaves the Mac.
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let maxCount = 30

    struct Entry: Equatable {
        let name: String      // file name in `dir`
        let date: Date
        let hash: String
        let pixelSize: CGSize
    }

    private(set) var entries: [Entry] = []
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var thumbCache: [String: NSImage] = [:]
    /// SHOTPARK_CLIPDIR points tests at a scratch folder + index so the user's history is untouched.
    private let testDir = ProcessInfo.processInfo.environment["SHOTPARK_CLIPDIR"]
    private var indexKey: String { testDir == nil ? "clipHistoryIndex" : "clipHistoryIndexTest" }

    static var isEnabled: Bool {
        get { UserDefaults.standard.object(forKey: "clipHistoryEnabled") == nil ? true : UserDefaults.standard.bool(forKey: "clipHistoryEnabled") }
        set {
            UserDefaults.standard.set(newValue, forKey: "clipHistoryEnabled")
            newValue ? shared.start() : shared.stop()
        }
    }

    var dir: URL {
        if let t = testDir {
            let d = URL(fileURLWithPath: t, isDirectory: true)
            try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
            return d
        }
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let d = base.appendingPathComponent("ShotPark/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
        return d
    }

    private init() { load() }

    // MARK: watching

    func start() {
        guard timer == nil, Self.isEnabled else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.7, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.3
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Check the pasteboard now (also used right after ShotPark itself copies).
    func poll() {
        guard timer != nil else { return } // not watching (turned off, or a test)
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard Self.isEnabled else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        // Password managers and the like mark secrets; never record those.
        if types.contains("org.nspasteboard.ConcealedType") || types.contains("org.nspasteboard.TransientType")
            || types.contains("org.nspasteboard.AutoGeneratedType") { return }
        // Only real image data (PNG/TIFF/…), not file references or rich text with an icon.
        guard pb.availableType(from: [.png, .tiff]) != nil, let image = NSImage(pasteboard: pb) else { return }
        add(image)
    }

    // MARK: storage

    @discardableResult
    func add(_ image: NSImage) -> Entry? {
        guard let png = Exporter.pngData(image) else { return nil }
        let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        if let i = entries.firstIndex(where: { $0.hash == hash }) {
            // Same image again: move it to the front.
            let e = entries.remove(at: i)
            let moved = Entry(name: e.name, date: Date(), hash: e.hash, pixelSize: e.pixelSize)
            entries.insert(moved, at: 0)
            save()
            return moved
        }
        let name = UUID().uuidString + ".png"
        do { try png.write(to: dir.appendingPathComponent(name)) } catch { return nil }
        let rep = NSBitmapImageRep(data: png)
        let size = CGSize(width: rep?.pixelsWide ?? Int(image.size.width), height: rep?.pixelsHigh ?? Int(image.size.height))
        let e = Entry(name: name, date: Date(), hash: hash, pixelSize: size)
        entries.insert(e, at: 0)
        while entries.count > Self.maxCount { deleteFile(entries.removeLast()) }
        save()
        return e
    }

    func remove(_ e: Entry) {
        entries.removeAll { $0.name == e.name }
        deleteFile(e)
        save()
    }

    func clear() {
        entries.forEach(deleteFile)
        entries = []
        save()
    }

    func url(_ e: Entry) -> URL { dir.appendingPathComponent(e.name) }
    func image(_ e: Entry) -> NSImage? { NSImage(contentsOf: url(e)) }

    func thumbnail(_ e: Entry, maxSide: CGFloat = 320) -> NSImage? {
        if let t = thumbCache[e.name] { return t }
        guard let src = NSImageRep(contentsOf: url(e)) else { return nil }
        let w = CGFloat(src.pixelsWide), h = CGFloat(src.pixelsHigh)
        guard w > 0, h > 0 else { return nil }
        let s = min(1, maxSide / max(w, h))
        let size = NSSize(width: max(1, w * s), height: max(1, h * s))
        let t = NSImage(size: size, flipped: false) { r in src.draw(in: r); return true }
        thumbCache[e.name] = t
        return t
    }

    /// Put an entry back on the clipboard (it moves to the front instead of being recorded twice).
    func copyToClipboard(_ e: Entry) {
        guard let img = image(e) else { return }
        Exporter.copy(img)
        lastChangeCount = NSPasteboard.general.changeCount // our own write: don't record it again
        if let i = entries.firstIndex(of: e) {
            entries.remove(at: i)
            entries.insert(Entry(name: e.name, date: Date(), hash: e.hash, pixelSize: e.pixelSize), at: 0)
            save()
        }
    }

    private func deleteFile(_ e: Entry) {
        thumbCache[e.name] = nil
        try? FileManager.default.removeItem(at: url(e))
    }

    private func save() {
        let arr: [[String: Any]] = entries.map {
            ["name": $0.name, "date": $0.date.timeIntervalSince1970, "hash": $0.hash,
             "w": Double($0.pixelSize.width), "h": Double($0.pixelSize.height)]
        }
        UserDefaults.standard.set(arr, forKey: indexKey)
        NotificationCenter.default.post(name: .clipboardHistoryChanged, object: nil)
    }

    private func load() {
        let arr = UserDefaults.standard.array(forKey: indexKey) as? [[String: Any]] ?? []
        entries = arr.compactMap { d in
            guard let name = d["name"] as? String, let t = d["date"] as? Double, let hash = d["hash"] as? String,
                  FileManager.default.fileExists(atPath: dir.appendingPathComponent(name).path) else { return nil }
            return Entry(name: name, date: Date(timeIntervalSince1970: t), hash: hash,
                         pixelSize: CGSize(width: d["w"] as? Double ?? 0, height: d["h"] as? Double ?? 0))
        }
    }
}
